// Builds the Kids app and the parent site, then assembles them into one static
// folder for a Cloudflare Pages Direct Upload:
//
//   node scripts/assemble-site.mjs            build both, then assemble
//   node scripts/assemble-site.mjs --no-build assemble the existing builds
//
// Output: artifacts/site-output/
//
// The Kids build goes to tmp/site-build/kids, never to
// artifacts/petit-mokus/dist/public, so the folder that holds the currently
// deployed site is left alone.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const kidsBuild = join(root, "tmp", "site-build", "kids");
const siteBuild = join(root, "artifacts", "site", "dist");
const out = join(root, "artifacts", "site-output");

// The Kids shell is served from here, and every non-English locale is
// rewritten to it. Cloudflare Pages ignores a rewrite whose target ends in
// index.html ("infinite loop"), so the rewrite uses the directory form.
const KIDS_SHELL = "en/kids/index.html";
const KIDS_REWRITE = "/en/kids/";

function run(command, args, env = {}) {
  execFileSync(command, args, { cwd: root, stdio: "inherit", env: { ...process.env, ...env } });
}

/** Every file under `dir`, as paths relative to `dir`. */
function files(dir, base = dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? files(full, base) : [relative(base, full)];
  });
}

/** The locale roots that serve Kids, read from the Kids app's own route table. */
function kidsLocales() {
  const source = readFileSync(join(root, "artifacts", "petit-mokus", "src", "App.tsx"), "utf8");
  const table = source.match(/const PATH_TO_LANGUAGE[^=]*=\s*\{([\s\S]*?)\};/);
  if (!table) throw new Error("Could not read PATH_TO_LANGUAGE from the Kids app");
  const locales = [...table[1].matchAll(/\b([a-z]{2,3}):\s*'/g)].map((m) => m[1]).filter((code) => code !== "en");
  if (locales.length === 0) throw new Error("No Kids locales found");
  return locales;
}

if (!process.argv.includes("--no-build")) {
  run(
    "pnpm",
    ["--filter", "@workspace/petit-mokus", "exec", "vite", "build", "--config", "vite.config.ts", "--outDir", kidsBuild, "--emptyOutDir"],
    { PORT: "3000", BASE_PATH: "/" },
  );
  run("pnpm", ["--filter", "@workspace/petit-mokus-site", "run", "build"], { ASTRO_TELEMETRY_DISABLED: "1" });
}
for (const dir of [kidsBuild, siteBuild]) if (!existsSync(dir)) throw new Error(`Missing build: ${dir}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

// 1. The Kids build goes in as it is, so /assets, the favicons and the audio
//    keep the root paths the app already uses.
cpSync(kidsBuild, out, { recursive: true });
//    Finder metadata that Vite copies from public/ is dropped.
for (const f of files(out)) if (f.split("/").pop() === ".DS_Store") rmSync(join(out, f), { force: true });
// 2. Its shell moves from the site root to the English Kids route.
mkdirSync(dirname(join(out, KIDS_SHELL)), { recursive: true });
renameSync(join(out, "index.html"), join(out, KIDS_SHELL));
// 3. The parent site owns routing and the sitemap; Kids' own copies are dropped.
for (const replaced of ["_redirects", "sitemap.xml"]) rmSync(join(out, replaced), { force: true });
// 4. The parent site is merged in. Any other overlap is a bug, not something to overwrite.
const clashes = files(siteBuild).filter((f) => existsSync(join(out, f)));
if (clashes.length) throw new Error(`The parent site would overwrite Kids files: ${clashes.join(", ")}`);
cpSync(siteBuild, out, { recursive: true });

// 5. One routing file. Rules apply before static files (first match wins),
//    so a language with a static homepage gets no catch-all, and there is
//    deliberately no /en/* catch-all: unknown paths get the 404 page.
//    Kids, in every language, is the one shell at /<locale>/kids/; a language
//    with a parent homepage serves it at /<locale>/ (with its Journal), and a
//    language without one sends every path to its Kids.
const locales = kidsLocales();
const homeLocales = ["en", ...locales].filter((code) => existsSync(join(out, code, "index.html")));
const kidsOnly = locales.filter((code) => !homeLocales.includes(code));

const redirects = [
  "# Petit Mokus routing. Generated by scripts/assemble-site.mjs: do not edit.",
  "/  /en/  302",
  "",
  "# Kids, in every language, at /<locale>/kids/ (one shell; the app reads the language from the path).",
  "/en/kids  /en/kids/  301",
  ...locales.flatMap((code) => [`/${code}/kids  /${code}/kids/  301`, `/${code}/kids/*  ${KIDS_REWRITE}  200`]),
  "",
  "# Languages with a parent homepage: /<locale>/ and its Journal are static pages.",
  ...homeLocales.map((code) => `/${code}  /${code}/  301`),
  "",
  "# Languages without a homepage: everything opens Kids.",
  ...kidsOnly.flatMap((code) => [`/${code}  /${code}/kids/  301`, `/${code}/*  /${code}/kids/  301`]),
  "",
].join("\n");
writeFileSync(join(out, "_redirects"), redirects);

// 6. Nothing private or stray may ship.
const stray = files(out).filter((f) =>
  /(^|\/)(node_modules|\.git|\.wrangler|\.astro|petitmokus-repo)(\/|$)|(^|\/)\.(env|dev\.vars|DS_Store|npmrc)|\.(map|pem|key)$|credential|history/i.test(f),
);
if (stray.length) throw new Error(`Files that must not ship: ${stray.join(", ")}`);
for (const required of [KIDS_SHELL, "en/index.html", "404.html", "robots.txt", "sitemap.xml", "_headers", "_redirects"]) {
  if (!existsSync(join(out, required))) throw new Error(`Missing from the assembled site: ${required}`);
}

console.log(`Assembled ${files(out).length} files into ${relative(root, out)} (${homeLocales.length} homepages, ${locales.length + 1} Kids languages).`);
